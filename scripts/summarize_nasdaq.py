"""Publish only completed, hash-verified real Nasdaq runs from explicit tags."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--tags', nargs='+', required=True)
p.add_argument('--output', default='benchmarks/nasdaq/FINAL_RESULTS.md')
a = p.parse_args()
base = ROOT / 'benchmarks/nasdaq'
census = json.loads((base / 'source-census.json').read_text())
assert all(s['complete'] for s in census)
reports = []
for tag in a.tags:
    paths = sorted((base / 'results').glob(tag + '-*.json'))
    if not paths:
        raise RuntimeError(f'No completed reports for {tag}')
    for path in paths:
        d = json.loads(path.read_text())
        assert d['release_build'] and d['timing_valid'], path
        assert d['records'] == d['verified_records'], path
        assert all(d[k]['verified_against_source'] for k in ['query', 'scan_query'] if d.get(k)), path
        if d['tier'] == 'full':
            assert d['records'] == sum(s['records'] for s in census), path
            assert [s['canonical_sha256'] for s in d['sources']] == [s['canonical_sha256'] for s in census], path
            assert all(s['complete'] for s in d['sources']), path
        reports.append((path, d))
# Fairness check across every target of the same tier. Windows are a separate
# declared corpus subset, not an extrapolation to the full source files.
for tier in {d['tier'] for _, d in reports}:
    hashes = {tuple((s['records'], s['canonical_sha256']) for s in d['sources'])
              for _, d in reports if d['tier'] == tier}
    assert len(hashes) == 1, f'Canonical stream mismatch: {tier}'
lines = ['# Verified Nasdaq release results', '',
         'Generated by `scripts/summarize_nasdaq.py` from completed release reports. No extrapolation.', '',
         '## Corpus', '',
         f"- Vendor DBN.zst bytes: {sum(s['source_file_bytes'] for s in census):,}.",
         f"- Observed uncompressed DBN bytes: {sum(s['decompressed_bytes_observed'] for s in census):,}.",
         f"- Canonical logical bytes: {sum(s['logical_bytes'] for s in census):,}.",
         f"- Records: {sum(s['records'] for s in census):,}.",
         f"- Distinct instruments: {len(set(i for s in census for i in s['instrument_ids'])):,}.",
         '- Schema: DBN v1, XNAS.ITCH MBO; all 15 fields, 56 canonical bytes per record; ts_out absent.', '',
         '## Method', '',
         'All targets receive the same ordered canonical records. Every represented field is reconstructed and checked by per-source SHA-256. Full runs additionally verify original source hashes and the complete census. Original transport files are preserved.', '',
         'Input representation is stated per run. Ingest includes source reading/hashing, outer Zstd decompression when applicable, DBN parsing, canonical rows, and target writing/close. Verified decode includes all-field reconstruction and SHA-256. Columnar scans are separate measurements without row reconstruction or hashing. Parquet uses Zstd3. Strata encode uses the declared workers; Parquet/fixed writers are serial. Parallel scan comparisons use equal worker counts.', '',
         'GB/MB are decimal. Target physical bytes include target framing/schema; original DBN metadata is retained separately and reported in target-plus-metadata bytes. Vendor transport is a full-corpus storage baseline only. Bits/value divides target bits by records × 15 fields, irrespective of field widths.', '',
         'Buffered I/O, OS-managed cache, no CPU affinity, fast durability without fsync guarantees. Physical MB/s is output bytes per ingest second, not a device counter. RSS/CPU/wall time cover the entire process including verification and queries. Query timings are Strata-only, without built indexes; no cross-engine query superiority is claimed.', '']
for path, d in reports:
    m, usage = d['metrics'], d.get('process_usage', {})
    lines += [f"## {d['tag']} / {d['tier']} / {d['profile']}", '',
              f"Source: [raw JSON](results/{path.name}); environment: [{d.get('environment')} ]({d.get('environment')}).", '',
              f"- Input: {d.get('source_representation', 'see source zstd flags')}; records: {d['records']:,}; logical bytes: {d['sizes']['logical_bytes']:,}.",
              f"- DBN accepted / observed bytes: {d['dbn_bytes_accepted']:,} / {d['dbn_bytes_observed']:,}.",
              f"- Target physical bytes: {d['sizes']['physical_bytes']:,}; with original DBN metadata: {d['target_plus_dbn_metadata_bytes']:,}.",
              f"- Semantic encoded bytes: {d.get('semantic_encoded_bytes') if d.get('semantic_encoded_bytes') is not None else 'not applicable'}.",
              f"- Compression: {m['compression_ratio']:.6f}×; bits/value: {m['bits_per_value']:.6f}.",
              f"- Ingest: {m['records_per_sec']:,.0f} records/s; {m['logical_gb_s']:.6f} logical GB/s; {m['disk_mb_s']:.3f} output MB/s; {d['encode_seconds']:.3f} seconds.",
              f"- Verified decode: {m['decode_records_per_sec']:,.0f} records/s; {m['decode_gb_s']:.6f} logical GB/s; {d['decode_seconds']:.3f} seconds."]
    for key in ['columnar_scan', 'parallel_columnar_scan']:
        if d.get(key):
            v = d[key]
            lines.append(f"- {key}: {v['records_per_sec']:,.0f} records/s; {v['logical_gb_s']:.6f} logical GB/s; workers: {v.get('workers', 1)}.")
    for key in ['query', 'scan_query']:
        if d.get(key):
            q = d[key]
            lines.append(f"- Verified query `{q['text']}`: {q['elapsed_seconds']:.6f} seconds; {q['records']:,} returned records.")
    lines += [f"- Whole-process wall seconds: {usage.get('wall_seconds')}; peak RSS bytes: {usage.get('peak_rss_bytes')}; CPU % of one core: {usage.get('cpu_percent_of_one_core')}.", '']
destination = ROOT / a.output
destination.write_text('\n'.join(lines) + '\n')
print(f'Published {len(reports)} verified runs to {destination}')
